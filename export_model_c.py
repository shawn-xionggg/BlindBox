"""
Export the trained early punch detector (scikit-learn gradient-boosted trees)
to plain C99, so the scoring step runs natively on QNX with no Python.

Generates:
  qnx/model/early_model.h   feature names/order, threshold(s), early_score()
  qnx/model/early_model.c   every tree as nested if/else

Each tree node: if the feature is NaN, follow the branch the model learned for
missing values; else go left when x <= threshold. Score = sigmoid(baseline +
sum of leaf values) -- identical to predict_proba[:, 1].

Then it compiles a small test with gcc and checks that C and Python agree on
real feature rows from the recorded sessions.

  python export_model_c.py [models/early_detector.joblib]
"""
import math
import os
import subprocess
import sys
from pathlib import Path

import joblib
import numpy as np

OUT = Path("qnx/model")


def cnum(v):
    """C literal for a double (scikit-learn uses +inf thresholds for 'missing vs not' splits)."""
    if math.isinf(v):
        return "INFINITY" if v > 0 else "(-INFINITY)"
    return f"{v:.17g}"


def emit_tree(nodes, idx, depth, lines):
    nd = nodes[idx]
    pad = "    " * depth
    if nd["is_leaf"]:
        lines.append(f"{pad}s += {float(nd['value']):.17g};")
        return
    f, thr = int(nd["feature_idx"]), float(nd["num_threshold"])
    miss_left = bool(nd["missing_go_to_left"])
    cond_nan = f"isnan(x[{f}])"
    if miss_left:
        cond = f"{cond_nan} || x[{f}] <= {cnum(thr)}"
    else:
        cond = f"!{cond_nan} && x[{f}] <= {cnum(thr)}"
    lines.append(f"{pad}if ({cond}) {{")
    emit_tree(nodes, int(nd["left"]), depth + 1, lines)
    lines.append(f"{pad}}} else {{")
    emit_tree(nodes, int(nd["right"]), depth + 1, lines)
    lines.append(f"{pad}}}")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "models/early_detector.joblib"
    b = joblib.load(path)
    clf, names = b["model"], b["names"]
    if clf.n_trees_per_iteration_ != 1:
        raise SystemExit("expected a binary classifier")
    if getattr(clf, "is_categorical_", None) is not None and np.any(clf.is_categorical_):
        raise SystemExit("categorical features not supported")
    base = float(np.ravel(clf._baseline_prediction)[0])
    OUT.mkdir(parents=True, exist_ok=True)

    h = [
        "/* Generated by export_model_c.py -- do not edit. */",
        "#ifndef EARLY_MODEL_H", "#define EARLY_MODEL_H", "",
        f"#define EARLY_N_FEATURES {len(names)}",
        f"#define EARLY_FLOW_SCALE {float(b.get('flow_scale', 0.5)):.4g}",
    ]
    for k, v in sorted(b["thresholds"].items()):
        h.append(f"#define EARLY_THRESHOLD_BUDGET_{int(round(float(k)))} {float(v):.9g}  /* false alarms/min budget */")
    h += ["", "/* feature order (x[i]); NaN = unknown/missing */",
          "static const char *const EARLY_FEATURE_NAMES[EARLY_N_FEATURES] = {"]
    h += [f'    "{n}",' for n in names]
    h += ["};", "",
          "/* Probability that this wrist has just launched a punch (0..1). */",
          "double early_score(const double x[EARLY_N_FEATURES]);", "", "#endif", ""]
    (OUT / "early_model.h").write_text("\n".join(h))

    c = ["/* Generated by export_model_c.py -- do not edit. */",
         "#include <math.h>", '#include "early_model.h"', ""]
    for ti, preds in enumerate(clf._predictors):
        nodes = preds[0].nodes
        c.append(f"static double tree_{ti}(const double *x) {{")
        c.append("    double s = 0.0;")
        lines = []
        emit_tree(nodes, 0, 1, lines)
        c += lines
        c.append("    return s;")
        c.append("}")
        c.append("")
    c.append("double early_score(const double x[EARLY_N_FEATURES]) {")
    c.append(f"    double raw = {base:.17g};")
    for ti in range(len(clf._predictors)):
        c.append(f"    raw += tree_{ti}(x);")
    c.append("    return 1.0 / (1.0 + exp(-raw));")
    c.append("}")
    c.append("")
    (OUT / "early_model.c").write_text("\n".join(c))
    print(f"wrote {OUT / 'early_model.h'} and {OUT / 'early_model.c'} ({len(clf._predictors)} trees)")

    # ---- verify: C vs Python on real rows ----
    import early_dataset
    rows = []
    for p in sorted(Path("data").glob("*.npz")):
        if p.with_suffix(".labels.json").exists() and p.with_suffix(".auto_candidates.json").exists():
            X = early_dataset.build(p)["X"].reshape(-1, len(names))
            rng = np.random.default_rng(0)
            rows.append(X[rng.choice(len(X), size=min(1500, len(X)), replace=False)])
    X = np.concatenate(rows)
    # include rows near/above threshold and fully-missing rows
    X = np.vstack([X, np.full((1, len(names)), np.nan)])
    np.savetxt(OUT / "test_rows.txt", X, fmt="%.17g")
    py = clf.predict_proba(X)[:, 1]
    test_c = OUT / "test_model.c"
    test_c.write_text(
        '#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n#include <math.h>\n#include "early_model.h"\n'
        "int main(int argc, char **argv) {\n"
        "    FILE *f = fopen(argv[1], \"r\"); if (!f) return 2;\n"
        "    double x[EARLY_N_FEATURES]; char tok[64];\n"
        "    for (;;) {\n"
        "        int i;\n"
        "        for (i = 0; i < EARLY_N_FEATURES; i++) {\n"
        "            if (fscanf(f, \"%63s\", tok) != 1) { fclose(f); return 0; }\n"
        "            x[i] = (strcmp(tok, \"nan\") == 0) ? NAN : strtod(tok, NULL);\n"
        "        }\n"
        "        printf(\"%.17g\\n\", early_score(x));\n"
        "    }\n}\n")
    exe = OUT / ("test_model.exe" if os.name == "nt" else "test_model")
    env = dict(os.environ)
    env["PATH"] = r"C:\msys64\ucrt64\bin;" + env.get("PATH", "")
    subprocess.run(["gcc", "-std=c99", "-O2", "-Wall", "-o", str(exe), str(test_c), str(OUT / "early_model.c"), "-lm"],
                   check=True, env=env)
    out = subprocess.run([str(exe), str(OUT / "test_rows.txt")], capture_output=True, text=True, check=True, env=env)
    cv = np.array([float(v) for v in out.stdout.split()])
    if len(cv) != len(py):
        raise SystemExit(f"row count mismatch: C {len(cv)} vs Python {len(py)}")
    err = np.max(np.abs(cv - py))
    thr = float(b["thresholds"][min(b["thresholds"], key=lambda k: abs(float(k) - 2.0))])
    flips = int(np.sum((cv > thr) != (py > thr)))
    print(f"C vs Python on {len(py)} real feature rows: max |diff| = {err:.2e}, "
          f"threshold decisions that differ = {flips}")
    if err > 1e-9 or flips:
        raise SystemExit("MISMATCH")
    print("OK: exported C model matches scikit-learn")


if __name__ == "__main__":
    main()
